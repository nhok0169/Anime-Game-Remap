def metadataVgMaps(char, folder):
    import json
    path = os.path.join(REPO, "Data", "Mod Downloads", "WuWa", char, folder, char + "Metadata.json")
    components = json.load(open(path, encoding = "utf-8"))["components"]
    return {slot: [component["vg_map"][str(i)] for i in range(len(component["vg_map"]))] for slot, component in enumerate(components)}


def vgMapRows():
    out = []
    for char, versions in VG_MAPS.items():
        for version, read in versions:
            out.append("        // " + char + "'s components' vertex groups in her merged skeleton at " + version + " (each component's vg_map)")
            for slot, groups in sorted(read().items()):
                pairs = ", ".join("{%d, %d}" % (i, g) for i, g in enumerate(groups))
                out.append("        {{" + cstr(version) + ", " + NAME(char) + ", " + cstr("component" + str(slot)) + ",\n          " + cstr(version) + ", "
                           + NAME(char) + ", \"\"},\n         VGRemap({" + pairs + "})},")
    return out


def missingHashRows():
    """The fixes' downloaded role hashes HashData.cpp lacks -- judged by the file's text OUTSIDE this block, not by the built
    module, which holds the block's own rows after a rebuild (judged so, a second run wrote an empty block)"""
    out = []
    text = open(os.path.join(DATA, "HashData.cpp"), encoding = "utf-8").read()
    text = re.sub(r"// ===== GENERATED: downloaded role hashes.*?// ===== END GENERATED: downloaded role hashes =====", "", text, flags = re.S)
    for char in CHARS:
        have = {h.lower() for line in text.splitlines() if "ModTypeId::" + char + ")" in line for h in re.findall(r'"([0-9a-fA-F]{8})"', line)}
        facts = parseConfig(char).textures
        version = "3.7" if facts.downloadVersionFolder == "3_7" else facts.downloadVersionFolder.replace("_", ".")
        for role, textureHash in sorted(dict(facts.fallbackTextures).items()):
            if textureHash.lower() not in have and len(textureHash) == 8 and all(ch in "0123456789abcdefABCDEF" for ch in textureHash):
                out.append("        // " + char + "'s " + role + " (a game texture the fix downloads)")
                out.append("        {{" + cstr(version) + ", " + NAME(char) + ", " + cstr(role) + "}, " + cstr(textureHash) + "},")   # (version, name, type)
    return out


KEPT = re.compile(r"        // ===== KEPT BY HAND: ([^(=\n]*?)(?: \([^)\n]*\))? =====\n.*?        // ===== END KEPT BY HAND: \1 =====\n", re.S)


def keptBlocks(path):
    """The blocks of rows a data file keeps by hand (a later game version's rows read off frame dumps, which no config
    holds): kept as they are when the file is rewritten"""
    if not os.path.exists(path):
        return []
    text = open(path, "rb").read().decode("utf-8").replace("\r\n", "\n")
    return [m.group(0).rstrip("\n") for m in KEPT.finditer(text)]


def writeData(name, rows, includes = (), extra = ""):
    path = os.path.join(DATA, name + ".cpp")
    rows = list(rows) + keptBlocks(path)
    text = HEADER.format(name = name, rows = "\n".join(rows), includes = "\n".join(includes) + extra)
    with open(path, "w", encoding = "utf-8", newline = "\r\n") as f:
        f.write(text)
    print("wrote", path, len(rows), "lines")


def writeBlock(file, rows, marker):
    path = os.path.join(DATA, file)
    text = open(path, "rb").read().decode("utf-8")
    crlf = "\r\n" in text
    text = text.replace("\r\n", "\n")
    begin, end = "        // ===== GENERATED: " + marker + " (genWWMIAssetData.py) =====\n", "        // ===== END GENERATED: " + marker + " =====\n"
    block = begin + "\n".join(rows) + "\n" + end
    if begin in text:
        a = text.index(begin)
        b = text.index(end, a) + len(end)
        text = text[:a] + block + text[b:]
    else:
        anchor = next(a for a in ("    };\n\n    return rows;\n}", "    };\n    return rows;\n}") if text.count(a) == 1)
        text = text.replace(anchor, "\n" + block + anchor)
    if crlf:
        text = text.replace("\n", "\r\n")
    open(path, "wb").write(text.encode("utf-8"))
    print("wrote block", marker, "into", file, len(rows), "lines")


