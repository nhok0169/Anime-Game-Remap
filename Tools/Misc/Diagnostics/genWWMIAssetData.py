SHADER_VERSION = "3.7"     # every one was read off a character-menu dump at game 3.7 (3.7.1 for Changli's)


def gameShaderRows():
    out, includes = [], []
    for char, parts in SHADERS.items():
        out.append("        // " + char + "'s game shaders (decompiled pixel shader, and the constants its draw read)")
        for part in parts:
            fn = char[0].lower() + char[1:] + part + "Shader"
            includes.append('#include "AGRemapCore/data/IniFixData/' + char + "/" + char + part + 'Shader.h"')
            out.append(row(SHADER_VERSION, char, "", char + part, fn + "().ps", True))
            # a row per constant buffer the shader's draw read (its register: ps-cb1, ps-cb4, ...), as its generated file defines them
            source = open(os.path.join(DATA, "IniFixData", char, char + part + "Shader.cpp"), encoding = "utf-8").read()
            for buffer in re.findall(r'constantBuffers\["([a-z0-9-]+)"\]', source):
                out.append(row(SHADER_VERSION, char, "", char + part + "." + buffer, "constantsOf(" + fn + "(), \"" + buffer + "\")", True))
    return out, includes


def dispatchRows():
    seen, out = set(), []
    for src, tgt, config in fixConfigs():
        if config.shapeKeyDispatchSize and (tgt, config.version) not in seen:
            seen.add((tgt, config.version))
            out.append(row(config.version, tgt, "", "dispatchY", config.shapeKeyDispatchSize))
    return out


def centroidRows():
    out = []
    for char in CHARS:
        parse = parseConfig(char)
        if not parse.referenceBoneCentroids:
            continue
        reference = next(n.version for n in parse.skeletonNumberings if not n.toReference)
        out.append("        // " + char + " (" + reference + "): each bone's rest-pose centroid on her own model, in that version's numbering")
        for bone, centroid in sorted(parse.referenceBoneCentroids.items()):
            out.append(row(reference, char, "", str(bone), ",".join("%.4f" % v for v in centroid)))
    return out


def shapeKeyRemapRows():
    out = []
    for src, tgt, config in fixConfigs():
        if config.shapeKeyOrder:
            fromVersion = config.sourceVersion or parseConfig(src).version
            out.append("        {{" + cstr(fromVersion) + ", " + NAME(src) + ", \"\", " + cstr(config.version) + ", " + NAME(tgt) + ", \"\"}, "
                       + cstr(",".join(str(k) for k in config.shapeKeyOrder)) + "},")
    return out


def numberingRows():
    """Each older numbering of a character's skeleton as a VGRemap onto the reference one: every bone of the older
    version's merged skeleton, the renumbered ones moved"""
    out = []
    for char in CHARS:
        parse = parseConfig(char)
        if len(parse.skeletonNumberings) < 2:
            continue
        reference = next(n.version for n in parse.skeletonNumberings if not n.toReference)
        S = F.ModTypes[char].value
        # the reference numbering onto itself first: a lookup answers with the newest row at or below the version asked,
        # so without it a mod already in the reference numbering would read the older numbering's renumbering
        for numbering in sorted(parse.skeletonNumberings, key = lambda n: bool(n.toReference)):
            version = F.Version.parse(numbering.version)
            bones, slot = 0, 0
            while S.getVGOffset("component" + str(slot), "", version) is not None:
                bones = max(bones, int(S.getVGOffset("component" + str(slot), "", version)) + int(S.getVGCount("component" + str(slot), "", version)))
                slot += 1
            bones = max([bones] + [b + 1 for b in numbering.toReference])
            remap = {b: numbering.toReference.get(b, b) for b in range(bones)}
            pairs = ", ".join("{%d, %d}" % (k, v) for k, v in remap.items())
            out.append("        // " + char + "'s skeleton " + ("renumbered from " + numbering.version + " to " + reference + " (her own bones; the others as they were)"
                                                       if numbering.toReference else "at " + reference + ", the reference numbering (every bone onto itself)"))
            out.append("        {{" + cstr(numbering.version) + ", " + NAME(char) + ", \"\",\n          " + cstr(reference) + ", " + NAME(char) + ", \"\"},\n         VGRemap({" + pairs + "})},")
    return out


