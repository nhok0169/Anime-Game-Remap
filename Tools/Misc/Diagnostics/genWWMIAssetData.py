def textureRegisterRows():
    """Per character: where her own draws bind each role (her parser's registerRoles), what her own game shaders read that
    those do not name (each fix's Shader::registers, on the source), and what each other pass of a target's slot reads
    (each fix's extraPassRegs, as <role>@<pass>: the role the TARGET names at the register the fix's main list binds it at,
    the pass named as DrawPasses names it). A row that cannot be derived so is printed, not written"""
    out, notes = [], []
    tables = {}
    for char in CHARS:
        parse = parseConfig(char)
        tables[char] = (parse.version, {slot: dict(table) for slot, table in parse.textures.registerRoles.items()})
    extra = {char: {} for char in CHARS}              # char -> {(slot, type): reg}

    typeOf = lambda reg, role: role + "@rabbitfx" if reg.startswith("Resource\\RabbitFX") else role

    def conflict(char, slot, type_, reg, rows):
        """Why (char, slot, type_) -> reg cannot join her table and 'rows' (None: it can, or it is there already)"""
        have = {typeOf(r, role): r for r, role in tables[char][1].get(slot, {}).items()}
        known = have.get(type_, rows.get((char, slot, type_)))
        if known is not None:
            return None if known == reg else "%s component%d %s at %s and %s" % (char, slot, type_, known, reg)
        taken = {r for r in have.values()} | {r for (c, s, t), r in rows.items() if c == char and s == slot and "@" not in t}
        if "@" not in type_ and reg in taken:
            return "%s component%d %s at %s, a register her table already gives a role" % (char, slot, type_, reg)
        return None

    def add(char, slot, type_, reg, why):
        rows = {(c, s, t): r for c in extra for (s, t), r in extra[c].items()}
        problem = conflict(char, slot, type_, reg, rows)
        if problem is not None:
            notes.append("skipped (%s): %s" % (why, problem))
        elif type_ not in {typeOf(r, role) for r, role in tables[char][1].get(slot, {}).items()}:
            extra[char][(slot, type_)] = reg

    for (char, slot, reg), role in TARGET_ONLY_ROLES.items():
        add(char, slot, role, reg, "TARGET_ONLY_ROLES")
    for (char, slot, reg), role in OTHER_PASS_ROLES.items():
        add(char, slot, role + "@other", reg, "OTHER_PASS_ROLES")
    for src, tgt, config in fixConfigs():
        _, targetRoles = tables[tgt]
        if (src, tgt) in PLAN_LAYOUTS:
            for key, entry in config.plan.items():
                for b in entry.bindings:
                    add(tgt, entry.slot, PLAN_LAYOUTS[(src, tgt)].get(b.role, b.role), b.reg, src + " -> " + tgt + "'s plan " + str(key))
        for key, entry in config.plan.items():
            for shader in [s for s in (entry.shader, entry.overlay) if s is not None and key < 100]:   # a reroute's shader is its source's
                for b in shader.registers:
                    add(src, key, b.role, b.reg, src + "'s " + shader.name)
                for reg, value in shader.lines:                   # a game texture it reads by role (her ramp)
                    if value.startswith("role "):
                        add(src, key, value[len("role "):], reg, src + "'s " + shader.name)
        # a pair's other passes are written all or none: a partial set would read as the whole of what the pass binds
        rows, problems = {}, []
        for slot, passes in config.extraPassRegs.items():
            named = TARGET_ONLY_ROLES_OF(tgt, slot) | targetRoles.get(slot, {})
            for i, (ps, bindings) in enumerate(passes.items()):
                passName = "other" if i == 0 else "other" + str(i + 1)
                for b in bindings:
                    plans = [config.plan[b.srcComponent]] if b.srcComponent >= 0 else [e for e in config.plan.values() if e.slot == slot]
                    regs = {bb.reg for e in plans for bb in e.bindings if bb.role == b.role}
                    roles = {named[r] for r in regs if r in named}
                    if len(roles) != 1:
                        problems.append("slot %d pass %s: %s at %s names target roles %s" % (slot, ps, b.role, b.reg, sorted(roles)))
                        continue
                    key = (tgt, slot, roles.pop() + "@" + passName)
                    problem = conflict(*key, b.reg, {**{(c, s, t): r for c in extra for (s, t), r in extra[c].items()}, **rows})
                    if problem is not None:
                        problems.append(problem)
                    rows[key] = b.reg
        if problems:
            notes.append("%s -> %s: other passes not written (%d of its bindings do not derive; first: %s)" % (src, tgt, len(problems), problems[0]))
        else:
            for (char, slot, type_), reg in rows.items():
                extra[char][(slot, type_)] = reg

    for tgt, version, mesh, role, reg in sharedMeshRows()[1]:
        out.append("        // " + tgt + "'s " + mesh + " mesh: what its pass binds")
        out.append(row(version, tgt, mesh, role, reg))
    for char in CHARS:
        version, roles = tables[char]
        if not roles and not extra[char]:
            continue
        out.append("        // " + char + " (" + version + "): where her own draws bind each role (RabbitFX's keys as <role>@rabbitfx)")
        for slot, table in sorted(roles.items()):
            for reg, role in table.items():
                type_ = role + "@rabbitfx" if reg.startswith("Resource\\RabbitFX") else role
                out.append(row(version, char, "component" + str(slot), type_, reg))
        if extra[char]:
            out.append("        // ...what her own game shaders read besides, and each other pass of her slots (<role>@<pass>)")
            for (slot, type_), reg in sorted(extra[char].items()):
                out.append(row(version, char, "component" + str(slot), type_, reg))
    for note in notes:
        print("TextureRegisters:", note)
    textureRegisterRows.extra = {(char, slot, type_, tables[char][0]): reg for char in extra for (slot, type_), reg in extra[char].items()}
    return out


