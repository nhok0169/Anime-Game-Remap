# What a character's own draws bind at ps-t0..t3 (DrawPasses' "<pass>.<register>" rows), and how the game creates those
# textures (TextureDescs): read off Lynae's frame dumps of 2026-10-04/05 (FrameAnalysis-Lynae*, at game 3.7 and Ultra
# High) -- each draw identified by the textures of its own roles, since her bangs and hair share both shaders; each
