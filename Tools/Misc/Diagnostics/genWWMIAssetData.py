"""genWWMIAssetData.py: generates the versioned WWMI asset tables' data files from the data the WWMI fixer and parser
configs carried until 2026-11-08 -- so the tables start out holding exactly what the compiled fixes used.

    py -3 genWWMIAssetData.py [--check]

Writes, under core/src/data:

    DrawPassData.cpp            DrawPasses: each target's draw passes per slot (WWMIFixerConfig::slotPasses,
                                passVertexShaders, extraPassRegs, the filter_index each vertex shader is tagged with)
    TextureRegisterData.cpp     TextureRegisters: where each character's own draws bind each texture role
                                (WWMIParserConfig::textures.registerRoles), what her own game shaders read besides
                                (WWMIFixerConfig::Shader::registers), and what each other pass of a target's slot reads
                                (extraPassRegs, as <role>@<pass>; a pair whose passes do not all derive is left out)
    GameShaderData.cpp          GameShaders: the game pixel shaders a fix draws a character's parts with, and the
                                constant buffers their draws read (the generated <Char><Part>Shader functions)
    ShapeKeyDispatchSizeData.cpp  ShapeKeyDispatchSizes: each target's shape-key dispatch height
    BoneCentroidData.cpp        BoneCentroids: each bone's rest-pose centroid (WWMIParserConfig::referenceBoneCentroids)
    ShapeKeyRemapData.cpp       ShapeKeyRemaps: the source key each target shape-key slot takes (shapeKeyOrder)
    MaterialCodeData.cpp        MaterialCodes: what a code map's bits mean (MATERIAL_CODES, below)
    MaterialColourData.cpp      MaterialColours: the colours a material mask marks a material with (MATERIAL_COLOURS)
    TextureDescData.cpp         TextureDescs: how the game creates a character's textures (TEXTURE_DESCS, from frame dumps)
    TextureThumbprintData.cpp   TextureThumbprints: each character's game textures' thumbprints (wwmiTextureThumbs.py)

and three generated blocks between markers: the skeleton numberings as VGRemapData rows (a character onto itself, an
older version onto the reference one, and the reference onto itself), her components' vertex group maps as VGRemapData
rows (each component onto her merged skeleton, VG_MAPS), and the role hashes HashData lacks that the fixes download.

--check reads every table back through the built module and compares it with the configs (after a rebuild).
"""
