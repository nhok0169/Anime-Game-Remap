"""wwmiFlagMask.py: where a character's own GAME material-code map carries some flag bits, as the block-majority bit
mask a ``WWMIFixerConfig::DrawReroute::sourceFlags`` holds -- a generated C++ file for the compiled fix and a JSON
file for the Python prototype.

    py -3 wwmiFlagMask.py --dds "Data/Mod Downloads/WuWa/Lynae/3_7/LynaeTexturec49bec43.dds" --flags 0x10 \
        --size 256 --func lynaePropsFilmFlags --header AGRemapCore/data/IniFixData/Lynae/LynaeFilmShader.h \
        --label "Lynae's props code map c49bec43, flag 0x10" --cpp <out .cpp> --json <out .json>

A reroute reads the MOD's own code map at each draw's vertices. A mod that binds none for that role draws on its own
character with the GAME's map, and this mask stands in for it: the map is cut into ``size x size`` blocks, and a
block is set when more than half of its texels carry any of the flags. A code is read the way the shader reads it:
the first channel, decoded and truncated when the map is stored sRGB. The texture is read through the API's own
``TextureFile``, so every format the fix can read is read the same way here.
"""
