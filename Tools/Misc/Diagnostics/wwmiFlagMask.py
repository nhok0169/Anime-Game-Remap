def shaderCode(byte, srgb):
    if not srgb:
        return byte
    c = byte / 255.0
    linear = (c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4) * 255.0
    return min(255, int(math.floor(linear + 1e-6)))


def mask(path, flags, size):
    tex = FRB.TextureFile(path)
    tex.open()
    if not tex.hasImage:
        raise SystemExit("cannot read " + path)
    w, h, px = tex.width, tex.height, tex.getPixels()
    if w % size or h % size:
        raise SystemExit("%d x %d does not divide into %d blocks" % (w, h, size))
    table = [shaderCode(b, tex.gamma is not None) & flags != 0 for b in range(256)]
    bw, bh = w // size, h // size
    counts = [0] * (size * size)
    for y in range(h):
        row = y * w * 4
        base = (y // bh) * size
        for x in range(0, w):
            if table[px[row + x * 4]]:
                counts[base + x // bw] += 1
    need = bw * bh / 2
    bits = bytearray((size * size + 7) // 8)
    for i, c in enumerate(counts):
        if c > need:
            bits[i // 8] |= 1 << (i % 8)
    return bits, sum(c > need for c in counts)


def cppText(args, bits):
    out = [CREDITS,
           "// GENERATED by Tools/Misc/Diagnostics/wwmiFlagMask.py -- do not edit by hand.",
           "// " + args.label + ": a " + str(args.size) + " x " + str(args.size) + " block-majority mask.",
           "",
           '#include "' + args.header + '"',
           "",
           "#include <cstdint>",
           "#include <vector>",
           "",
           "",
           "namespace AGRemapCore {",
           "    WWMIFixerConfig::DrawReroute::FlagMask " + args.func + "() {",
           "        WWMIFixerConfig::DrawReroute::FlagMask mask;",
           "        mask.width = %d;" % args.size,
           "        mask.height = %d;" % args.size,
           "        mask.bits = std::vector<std::uint8_t>{"]
    for i in range(0, len(bits), 24):
        out.append("            " + ", ".join("0x%02x" % b for b in bits[i:i + 24]) + ",")
    out += ["        };", "        return mask;", "    }", "}", ""]
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dds", required=True)
    p.add_argument("--flags", required=True, type=lambda s: int(s, 0))
    p.add_argument("--size", type=int, default=256)
    p.add_argument("--func")
    p.add_argument("--header")
    p.add_argument("--label", default="")
    p.add_argument("--cpp")
    p.add_argument("--json")
    args = p.parse_args()

    bits, set_ = mask(args.dds, args.flags, args.size)
    print("%d of %d blocks set" % (set_, args.size * args.size))
    if args.cpp:
        open(args.cpp, "wb").write(cppText(args, bits).replace("\n", "\r\n").encode("utf-8"))
        print("wrote", args.cpp)
    if args.json:
        data = {"width": args.size, "height": args.size, "bits": list(bits)}
        open(args.json, "w", encoding="utf-8", newline="\n").write(json.dumps(data) + "\n")
        print("wrote", args.json)


if __name__ == "__main__":
    main()
