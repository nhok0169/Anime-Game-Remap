#
# ===== changliPortTables =====
#
# Writes the compiled Changli -> ChangliNymph fix's data out of the prototype (changliNymphFix.py), so the
# port stays a transcription of the oracle rather than a retyping of it:
#
#   core/src/data/IniFixData/Changli/ChangliSkeleton.cpp   her renumberings, bone centroids, vg maps and
#                                                          the skin's shape-key slot order
#   <out>/changliRoles.txt                                 the role table, for ChangliTextures.cpp
#   <out>/changliOldRows.txt                               the 1.1 / 1.2 VGRemapData rows
#
#   py -3 changliPortTables.py <scratch folder for the two .txt files>
#
import os
import sys

Here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, Here)
import changliNymphFix as P      # noqa: E402

Credits = """// ##### Credits

// ===== Anime Game Remap (AG Remap) =====
// Authors: Albert Gold#2696, NK#1321
//
// if you used it to remap your mods pls give credit for "Albert Gold#2696" and "Nhok0169"
// Special Thanks:
//   nguen#2011 (for support)
//   SilentNightSound#7430 (for internal knowdege so wrote the blendCorrection code)
//   HazrateGolabi#1364 (for being awesome, and improving the code)

// ##### EndCredits
"""


def rows(pairs, perLine):
    items = list(pairs)
    return ",\n".join("            " + ", ".join(items[i:i + perLine]) for i in range(0, len(items), perLine))


def main():
    out = sys.argv[1]
    core = os.path.join(P.Repo, "Anime Game Remap (for all users)", "api", "src", "cpp", "core")

    renum11 = {b: P.toCurrent("1.1", b) for b in range(P.OldSkeletonSlots) if P.toCurrent("1.1", b) != b}
    renum12 = dict(P.Renumber12To14)
    centroids = P.boneCentroids()
    vgMaps = P.currentVgMaps()
    order = [-1] * 14 + list(range(72))

    text = Credits + """
// Generated by Tools/Misc/Prototypes/changliPortTables.py from changliNymphFix.py's tables -- regenerate
// rather than hand-edit, so the compiled fix stays the prototype's. Her two renumberings are the community
// wwmi_fix_23's (WWMI_FIX_23.py, the remaps it applies to her mods' Blend.buf), composed onto 1.4's ids.

#include "AGRemapCore/data/IniFixData/Changli/ChangliSkeleton.h"


namespace AGRemapCore {
    const std::unordered_map<long long, long long>& changliRenumbered11To14() {
        static const std::unordered_map<long long, long long> table = {
""" + rows((f"{{{a}, {b}}}" for a, b in sorted(renum11.items())), 10) + """
        };
        return table;
    }

    const std::unordered_map<long long, long long>& changliRenumbered12To14() {
        static const std::unordered_map<long long, long long> table = {
""" + rows((f"{{{a}, {b}}}" for a, b in sorted(renum12.items())), 10) + """
        };
        return table;
    }

    const std::unordered_map<long long, std::array<double, 3>>& changliBoneCentroids() {
        static const std::unordered_map<long long, std::array<double, 3>> table = {
""" + rows((f"{{{b}, {{{c[0]:.4f}, {c[1]:.4f}, {c[2]:.4f}}}}}" for b, c in sorted(centroids.items())), 3) + """
        };
        return table;
    }

    const std::map<int, std::vector<int>>& changliVgMaps() {
        static const std::map<int, std::vector<int>> table = {
""" + ",\n".join(f"            {{{k}, {{{', '.join(str(x) for x in v)}}}}}" for k, v in sorted(vgMaps.items())) + """
        };
        return table;
    }

    const std::vector<long long>& changliToNymphShapeKeys() {
        static const std::vector<long long> table = {
""" + rows((str(x) for x in order), 20) + """
        };
        return table;
    }
}
"""
    path = os.path.join(core, "src", "data", "IniFixData", "Changli", "ChangliSkeleton.cpp")
    os.makedirs(os.path.dirname(path), exist_ok = True)
    with open(path, "w", encoding = "utf-8", newline = "\r\n") as f:
        f.write(text)
    print("wrote", path)

    roles = P.allRoles()
    with open(os.path.join(out, "changliRoles.txt"), "w", encoding = "utf-8") as f:
        for h, role in sorted(roles.items(), key = lambda kv: (kv[1], kv[0])):
            f.write(f'            {{"{h}", "{role}"}},\n')

    P.FRB  # the API is imported by the prototype
    source = P.FRB.WWMIBuilder.changli()
    current = dict(source.getVGRemap(P.DstName, P.FRB.Version.parse("1.4"), P.FRB.Version.parse("2.4")).remap)
    with open(os.path.join(out, "changliOldRows.txt"), "w", encoding = "utf-8") as f:
        for version in ("1.1", "1.2"):
            old = {bone: current.get(P.toCurrent(version, bone), 0) for bone in range(P.OldSkeletonSlots)}
            f.write(f'        {{{{"{version}", ModTypeIdTools::getName(ModTypeId::Changli), "",\n'
                    f'          "2.4", ModTypeIdTools::getName(ModTypeId::ChangliNymph), ""}},\n         VGRemap({{\n')
            f.write(rows((f"{{{a}, {b}}}" for a, b in sorted(old.items())), 10) + "\n         })},\n\n")
    print("wrote the role table and the old rows into", out)


if (__name__ == "__main__"):
    main()
