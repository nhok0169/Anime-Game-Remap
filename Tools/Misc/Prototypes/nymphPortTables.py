#
# ===== nymphPortTables =====
#
# Generates the C++ tables of the ChangliNymph -> Changli port out of the prototype nymphChangliFix.py, so the
# compiled fix cannot drift from the oracle: ChangliNymph's texture facts (roles, register roles, fallbacks) in
# core/src/data/IniFixData/ChangliNymph/ChangliNymphTextures.cpp, and her per-component vg maps (a mod from before
# WWMI's merged skeleton) in .../ChangliNymphSkeleton.cpp. Her thumbprints come from
# Tools/Misc/Diagnostics/wwmiTextureThumbs.py.
#
#   py -3 nymphPortTables.py
#

import os
import sys

Here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, Here)
sys.argv = [sys.argv[0]]
import nymphChangliFix as N     # noqa: E402

Core = os.path.join(N.Repo, "Anime Game Remap (for all users)", "api", "src", "cpp", "core", "src", "data", "IniFixData", "ChangliNymph")

Credits = """// ##### Credits

// ===== Anime Game Remap (AG Remap) =====
// Authors: Albert Gold#2696, NK#1321
//
// if you used it to remap your mods pls give credit for "Albert Gold#2696" and "Nhok0169"
// Special Thanks:
//   nguen#2011 (for support)
//   SilentNightSound#7430 (for internal knowdege so wrote the blendCorrection code)
//   HazrateGolabi#1364 (for being awesome, and improving the code)

// ##### EndCredits
"""


def cstr(s):
    return '"' + s.replace("\\", "\\\\") + '"'


def write(path, text):
    with open(path, "w", encoding = "utf-8", newline = "\r\n") as f:
        f.write(text)
    print("wrote", path)


def textures():
    roles = N.allRoles()
    facts = N.textureFacts()
    lines = [Credits, "",
             '#include "AGRemapCore/data/IniFixData/ChangliNymph/ChangliNymphTextures.h"',
             '#include "AGRemapCore/data/IniFixData/ChangliNymph/ChangliNymphThumbprints.h"',
             "", "", "namespace AGRemapCore {", "",
             "    WWMITextureFacts changliNymphTextureFacts() {",
             "        WWMITextureFacts facts;", "",
             "        // ---- her textures by hash: WWMI-Assets' (ChangliSkin1, 2.7), the LIVE twin of each (Data/Mod",
             "        // Downloads/WuWa/ChangliNymph/ChangliNymphLiveHashes.json) and the textures only the 3.7 dump holds.",
             "        // Generated by Tools/Misc/Prototypes/nymphPortTables.py from nymphChangliFix.py's allRoles() ----",
             "        facts.roles = {"]
    for h, role in sorted(roles.items(), key = lambda kv: (kv[1], kv[0])):
        lines.append(f"            {{{cstr(h)}, {cstr(role)}}},")
    lines += ["        };", "",
              "        // ---- which role each of HER registers binds, per component (her own draws, wwmiPassLayout.py),",
              "        // plus RabbitFX's resource names (the Lightmap is the mask) ----",
              "        facts.registerRoles = {"]
    for comp, regs in sorted(N.RegisterRoles.items()):
        body = ", ".join(f"{{{cstr(r)}, {cstr(role)}}}" for r, role in regs.items())
        lines.append(f"            {{{comp}, {{{body}}}}},")
    lines += ["        };", "",
              "        // ---- her own textures' pixels, for a file no hash and no register names ----",
              "        facts.textureThumbprints = changliNymphTextureThumbprints();", "",
              "        // ---- a role the mod ships no file for falls back to HER game texture; the hair map and the eye",
              "        // textures are the same hashes on both outfits, so the game already binds them on Changli ----",
              f"        facts.downloadGameFolder = {cstr(facts.downloadGameFolder)};",
              f"        facts.downloadCharFolder = {cstr(facts.downloadCharFolder)};",
              f"        facts.downloadVersionFolder = {cstr(facts.downloadVersionFolder)};",
              f"        facts.downloadPrefix = {cstr(facts.downloadPrefix)};",
              "        facts.fallbackTextures = {"]
    for role, h in sorted(facts.fallbackTextures.items()):
        lines.append(f"            {{{cstr(role)}, {cstr(h)}}},")
    lines += ["        };", "", "        return facts;", "    }", "}", ""]
    write(os.path.join(Core, "ChangliNymphTextures.cpp"), "\n".join(lines))


def skeleton():
    maps = N.currentVgMaps()
    lines = [Credits, "",
             '#include "AGRemapCore/data/IniFixData/ChangliNymph/ChangliNymphSkeleton.h"',
             "", "", "namespace AGRemapCore {",
             "    // GENERATED by Tools/Misc/Prototypes/nymphPortTables.py from ChangliNymphMetadata.json -- do not edit by hand.",
             "    const std::map<int, std::vector<int>>& changliNymphVgMaps() {",
             "        static const std::map<int, std::vector<int>> maps = {"]
    for comp, m in sorted(maps.items()):
        rows = [", ".join(str(x) for x in m[i:i + 20]) for i in range(0, len(m), 20)]
        lines.append(f"            {{{comp}, {{")
        lines += [f"                {r}," for r in rows]
        lines.append("            }},")
    lines += ["        };", "        return maps;", "    }", "}", ""]
    write(os.path.join(Core, "ChangliNymphSkeleton.cpp"), "\n".join(lines))


if (__name__ == "__main__"):
    textures()
    skeleton()
